using System.Text;
using System.Xml;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using Passenger.Core;

namespace Passenger.Analyzers;

/// <summary>Each neutral .resx of a project's words as members of its home class, named for the file and its folder under
/// the project's root namespace (Refusals.resx beside Refusals.cs fills Passenger.App.Refusals), which is public, static and
/// partial: a member of type Words for each key, a property for words with no argument and a method with a parameter for
/// each argument of a message (a plural's or number's a double, a select's a string, a date's or time's a DateTimeOffset,
/// any other Words), its English in its documentation. A resource's culture files (xlf/Name.fr.xlf) name the languages
/// the assembly carries, said by its CarriedLanguages attribute, and each is held in step with its English: the same keys
/// in order, each unit's source the English as it stands (just words marks a translation older than its English, which
/// shows only while its arguments are still the English's), and a translation's arguments the English's.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class WordsResources : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<WordsFile> files = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith(".resx", StringComparison.OrdinalIgnoreCase) && Path.GetFileName(file.Path).Count(c => c == '.') == 1)
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select((pair, cancel) => Read(pair.Left, pair.Right.GlobalOptions, cancel))
            .Where(file => file is not null)!;
        context.RegisterSourceOutput(files, Write);
        IncrementalValueProvider<System.Collections.Immutable.ImmutableArray<Translation>> translations = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith(".xlf", StringComparison.OrdinalIgnoreCase))
            .Select((file, cancel) => Translation.Read(file, cancel))
            .Collect();
        context.RegisterSourceOutput(files.Combine(translations), (output, pair) => Check(output, pair.Left, pair.Right));
        IncrementalValueProvider<IReadOnlyList<string>> cultures = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith(".xlf", StringComparison.OrdinalIgnoreCase))
            .Select((file, _) => Path.GetFileNameWithoutExtension(file.Path))
            .Collect()
            .Select((names, _) => (IReadOnlyList<string>)[.. names.Select(n => n.Substring(n.LastIndexOf('.') + 1)).Where(c => c.Length > 0)
                .Distinct(StringComparer.OrdinalIgnoreCase).OrderBy(c => c, StringComparer.Ordinal)]);
        context.RegisterSourceOutput(cultures, (output, carried) =>
        {
            if (carried.Count > 0)
            {
                output.AddSource("CarriedLanguages.g.cs", "// <auto-generated/>\n[assembly: global::Passenger.Core.CarriedLanguages("
                    + string.Join(", ", carried.Select(c => SymbolDisplay.FormatLiteral(c, quote: true))) + ")]\n");
            }
        });
    }

    private static WordsFile? Read(AdditionalText file, Microsoft.CodeAnalysis.Diagnostics.AnalyzerConfigOptions options, CancellationToken cancel)
    {
        if (!options.TryGetValue("build_property.RootNamespace", out string? root) || root.Length == 0
            || !options.TryGetValue("build_property.MSBuildProjectDirectory", out string? project) || project.Length == 0)
        {
            return null;
        }
        string folder = Path.GetDirectoryName(Path.GetFullPath(file.Path)) ?? string.Empty;
        string under = Path.GetFullPath(project).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
        if (!folder.StartsWith(under, StringComparison.OrdinalIgnoreCase))
        {
            return null;
        }
        IEnumerable<string> folders = folder.Substring(under.Length).Split([Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar], StringSplitOptions.RemoveEmptyEntries);
        string space = string.Join(".", new[] { root }.Concat(folders));
        SourceText? text = file.GetText(cancel);
        List<WordsEntry> entries = [];
        string? problem = null;
        try
        {
            using XmlReader reader = XmlReader.Create(new StringReader(text?.ToString() ?? string.Empty));
            IXmlLineInfo lines = (IXmlLineInfo)reader;
            while (reader.Read())
            {
                if (reader.NodeType == XmlNodeType.Element && reader.LocalName == "data" && reader.GetAttribute("type") is null
                    && reader.GetAttribute("mimetype") is null && reader.GetAttribute("name") is { } name)
                {
                    int line = lines.LineNumber;
                    string? value = null;
                    using XmlReader data = reader.ReadSubtree();
                    while (data.Read())
                    {
                        if (data.NodeType == XmlNodeType.Element && data.LocalName == "value")
                        {
                            value = data.ReadElementContentAsString();
                            break;
                        }
                    }
                    entries.Add(new WordsEntry(name, value ?? string.Empty, line));
                }
            }
        }
        catch (XmlException e)
        {
            problem = e.Message;
        }
        return new WordsFile(file.Path, space, Path.GetFileNameWithoutExtension(file.Path), entries, problem, text);
    }

    private static void Write(SourceProductionContext output, WordsFile file)
    {
        if (file.Problem is not null)
        {
            output.ReportDiagnostic(Diagnostic.Create(Rules.WordsUnread, Location.None, Path.GetFileName(file.Path), file.Problem));
            return;
        }
        StringBuilder source = new();
        source.Append("// <auto-generated/>\n#nullable enable\nnamespace ").Append(file.Namespace).Append(";\n\n")
            .Append("/// <summary>The words of ").Append(Path.GetFileName(file.Path)).Append(", each a Words resolved in the language it is said in (Passenger.Analyzers' WordsResources).</summary>\n")
            .Append("public static partial class ").Append(file.Class).Append("\n{\n")
            .Append("    private static global::System.Resources.ResourceManager WordsResources => field ??= new(\"")
            .Append(file.Namespace).Append('.').Append(file.Class).Append("\", typeof(").Append(file.Class).Append(").Assembly);\n");
        HashSet<string> named = new(StringComparer.Ordinal);
        foreach (WordsEntry entry in file.Entries)
        {
            if (!SyntaxFacts.IsValidIdentifier(entry.Name) || SyntaxFacts.GetKeywordKind(entry.Name) != SyntaxKind.None || !named.Add(entry.Name))
            {
                output.ReportDiagnostic(Diagnostic.Create(Rules.WordsUnread, At(file, entry), Path.GetFileName(file.Path),
                    $"{entry.Name} is no C# name, or is named twice"));
                continue;
            }
            MessagePattern pattern;
            try
            {
                pattern = MessagePattern.Parse(entry.Value);
            }
            catch (FormatException e)
            {
                output.ReportDiagnostic(Diagnostic.Create(Rules.WordsUnread, At(file, entry), Path.GetFileName(file.Path), $"{entry.Name}: {e.Message}"));
                continue;
            }
            source.Append("\n    /// <summary>").Append(Documented(entry.Value)).Append("</summary>\n    public static global::Passenger.Core.Words ").Append(entry.Name);
            if (pattern.Arguments.Count == 0)
            {
                source.Append(" => field ??= new(WordsResources, \"").Append(entry.Name).Append("\");\n");
                continue;
            }
            source.Append('(').Append(string.Join(", ", pattern.Arguments.Select(a => $"{TypeOf(a.Kind)} {Parameter(a.Name)}"))).Append(") =>\n        new(WordsResources, \"")
                .Append(entry.Name).Append("\", ")
                .Append(string.Join(", ", pattern.Arguments.Select(a => $"(\"{a.Name}\", {Parameter(a.Name)})"))).Append(");\n");
        }
        source.Append("}\n");
        output.AddSource($"{file.Namespace}.{file.Class}.Words.g.cs", source.ToString());
    }

    /// <summary>Reports each of the file's translations out of step with it.</summary>
    private static void Check(SourceProductionContext output, WordsFile file, IReadOnlyList<Translation> translations)
    {
        string folder = Path.Combine(Path.GetDirectoryName(file.Path) ?? string.Empty, "xlf");
        Dictionary<string, WordsEntry> english = file.Entries.GroupBy(e => e.Name, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        foreach (Translation translation in translations.Where(t => string.Equals(Path.GetDirectoryName(t.Path), folder, StringComparison.OrdinalIgnoreCase)
            && Path.GetFileName(t.Path).StartsWith(file.Class + ".", StringComparison.Ordinal) && Path.GetFileName(t.Path).Count(c => c == '.') == 2))
        {
            void Report(int line, string what) => output.ReportDiagnostic(Diagnostic.Create(Rules.WordsOutOfStep,
                Location.Create(translation.Path, default, new LinePositionSpan(new LinePosition(Math.Max(0, line - 1), 0), new LinePosition(Math.Max(0, line - 1), 0))),
                Path.GetFileName(translation.Path), what));
            if (translation.Problem is not null)
            {
                Report(1, translation.Problem);
                continue;
            }
            if (!translation.Units.Select(u => u.Id).SequenceEqual(file.Entries.Select(e => e.Name)))
            {
                Report(1, $"its keys are not {Path.GetFileName(file.Path)}'s, in its order: run just words");
                continue;
            }
            foreach (TranslationUnit unit in translation.Units)
            {
                string source = english[unit.Id].Value;
                if (unit.Source != source)
                {
                    Report(unit.Line, $"{unit.Id}'s English changed: run just words, which marks its translation for review");
                }
                else if (unit.Target is { Length: > 0 } target && unit.State is not ("new" or "needs-review-translation") && Mismatch(source, target) is { } mismatch)
                {
                    Report(unit.Line, $"{unit.Id}'s translation {mismatch}");
                }
            }
        }
    }

    /// <summary>Why a translation can't stand for its English: it is no message, or names other arguments; null where it can.</summary>
    private static string? Mismatch(string english, string translated)
    {
        try
        {
            string[] wanted = [.. MessagePattern.Parse(english).Arguments.Select(a => a.Name).OrderBy(n => n, StringComparer.Ordinal)];
            string[] named = [.. MessagePattern.Parse(translated).Arguments.Select(a => a.Name).OrderBy(n => n, StringComparer.Ordinal)];
            return wanted.SequenceEqual(named) ? null : $"names {{{string.Join("}, {", named)}}} where its English names {{{string.Join("}, {", wanted)}}}";
        }
        catch (FormatException e)
        {
            return $"is no message: {e.Message}";
        }
    }

    private static string TypeOf(ArgumentKind kind) => kind switch
    {
        ArgumentKind.Number or ArgumentKind.Plural => "double",
        ArgumentKind.Select => "string",
        ArgumentKind.Date or ArgumentKind.Time => "global::System.DateTimeOffset",
        _ => "global::Passenger.Core.Words",
    };

    private static string Parameter(string name) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    /// <summary>A message's English as a documentation comment holds it: on one line, its markup's characters escaped.</summary>
    private static string Documented(string value) =>
        value.Replace("\r", " ").Replace("\n", " ").Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private static Location At(WordsFile file, WordsEntry entry)
    {
        if (file.Text is null || entry.Line < 1 || entry.Line > file.Text.Lines.Count)
        {
            return Location.None;
        }
        TextSpan span = file.Text.Lines[entry.Line - 1].Span;
        return Location.Create(file.Path, span, file.Text.Lines.GetLinePositionSpan(span));
    }
}

/// <summary>A neutral .resx's words as read: its path, the namespace and class it fills, its entries, why it could not be
/// read (null where it was) and its text, for a report's place.</summary>
internal sealed class WordsFile(string path, string @namespace, string @class, IReadOnlyList<WordsEntry> entries, string? problem, SourceText? text)
{
    public string Path { get; } = path;

    public string Namespace { get; } = @namespace;

    public string Class { get; } = @class;

    public IReadOnlyList<WordsEntry> Entries { get; } = entries;

    public string? Problem { get; } = problem;

    public SourceText? Text { get; } = text;
}

/// <summary>One key of a .resx: its name, its English and the line its data element starts on.</summary>
internal sealed class WordsEntry(string name, string value, int line)
{
    public string Name { get; } = name;

    public string Value { get; } = value;

    public int Line { get; } = line;
}

/// <summary>A translation as read from its XLIFF file: its units in order, or why it could not be read.</summary>
internal sealed class Translation(string path, IReadOnlyList<TranslationUnit> units, string? problem)
{
    private const string Xliff = "urn:oasis:names:tc:xliff:document:1.2";

    public string Path { get; } = path;

    public IReadOnlyList<TranslationUnit> Units { get; } = units;

    public string? Problem { get; } = problem;

    public static Translation Read(AdditionalText file, CancellationToken cancel)
    {
        List<TranslationUnit> units = [];
        try
        {
            using XmlReader reader = XmlReader.Create(new StringReader(file.GetText(cancel)?.ToString() ?? string.Empty));
            IXmlLineInfo lines = (IXmlLineInfo)reader;
            while (reader.Read())
            {
                if (reader.NodeType == XmlNodeType.Element && reader.LocalName == "trans-unit" && reader.NamespaceURI == Xliff && reader.GetAttribute("id") is { } id)
                {
                    int line = lines.LineNumber;
                    string? source = null;
                    string? target = null;
                    string? state = null;
                    using XmlReader unit = reader.ReadSubtree();
                    while (unit.Read())
                    {
                        if (unit.NodeType == XmlNodeType.Element && unit.LocalName == "source")
                        {
                            source = unit.ReadElementContentAsString();
                        }
                        if (unit.NodeType == XmlNodeType.Element && unit.LocalName == "target")
                        {
                            state = unit.GetAttribute("state");
                            target = unit.ReadElementContentAsString();
                        }
                    }
                    units.Add(new TranslationUnit(id, source ?? string.Empty, target, state, line));
                }
            }
        }
        catch (XmlException e)
        {
            return new Translation(file.Path, units, e.Message);
        }
        return new Translation(file.Path, units, null);
    }
}

/// <summary>One unit of a translation: its key, the English it was made from, its words in the language (null with none),
/// their state and the line it starts on.</summary>
internal sealed class TranslationUnit(string id, string source, string? target, string? state, int line)
{
    public string Id { get; } = id;

    public string Source { get; } = source;

    public string? Target { get; } = target;

    public string? State { get; } = state;

    public int Line { get; } = line;
}
