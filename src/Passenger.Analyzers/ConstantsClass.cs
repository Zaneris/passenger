using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Passenger.Analyzers;

/// <summary>A generated public static class of string constants in namespace Passenger, marked [IdentifierHome], each value
/// written as a C# literal whatever it holds: what ResourceKeys and StyleClassNames make of their files.</summary>
internal static class ConstantsClass
{
    /// <summary>Adds the class <paramref name="name"/> of every file's constants, each name once, in the files' order or,
    /// where <paramref name="sorted"/>, by name. A file that could not be read, two values making one name, and a value
    /// making no C# name are each reported as <paramref name="unread"/>; <paramref name="summary"/> is the class's
    /// documentation, given the files' names.</summary>
    public static void Write(SourceProductionContext output, string name, IReadOnlyList<ConstantsFile> files, DiagnosticDescriptor unread,
        bool sorted, Func<string, string> summary)
    {
        Dictionary<string, string> taken = new(StringComparer.Ordinal);
        List<(string Member, string Value)> members = [];
        foreach (ConstantsFile file in files)
        {
            if (file.Problem is not null)
            {
                output.ReportDiagnostic(Diagnostic.Create(unread, Location.None, file.Name, name, file.Problem));
                continue;
            }
            foreach ((string member, string value) in file.Constants)
            {
                if (taken.TryGetValue(member, out string? other))
                {
                    if (other != value)
                    {
                        output.ReportDiagnostic(Diagnostic.Create(unread, Location.None, file.Name, name,
                            $"\"{value}\" and \"{other}\" would both be {member}"));
                    }
                    continue;
                }
                if (!SyntaxFacts.IsValidIdentifier(member))
                {
                    output.ReportDiagnostic(Diagnostic.Create(unread, Location.None, file.Name, name,
                        $"\"{value}\" makes no C# name"));
                    continue;
                }
                taken[member] = value;
                members.Add((member, value));
            }
        }
        StringBuilder text = new();
        IEnumerable<(string Member, string Value)> written = sorted ? members.OrderBy(m => m.Member, StringComparer.Ordinal) : members;
        foreach ((string member, string value) in written)
        {
            text.Append("        public const string ").Append(member).Append(" = ").Append(SymbolDisplay.FormatLiteral(value, quote: true)).AppendLine(";");
        }
        output.AddSource($"{name}.g.cs", SourceText.From($$"""
            // <auto-generated/>
            namespace Passenger
            {
                /// <summary>{{summary(string.Join(", ", files.Select(f => f.Name).Distinct()))}}</summary>
                [global::Passenger.IdentifierHome]
                public static class {{name}}
                {
            {{text}}    }
            }
            """, Encoding.UTF8));
    }
}

/// <summary>What one file gives a constants class: its constants, each a member's name and its value, in the file's order,
/// or why it could not be read.</summary>
internal sealed class ConstantsFile(string @class, string name, IReadOnlyList<(string Member, string Value)> constants, string? problem)
{
    /// <summary>The class its constants go in.</summary>
    public string Class { get; } = @class;

    /// <summary>The file's name, for the class's documentation and a report.</summary>
    public string Name { get; } = name;

    public IReadOnlyList<(string Member, string Value)> Constants { get; } = constants;

    public string? Problem { get; } = problem;
}
