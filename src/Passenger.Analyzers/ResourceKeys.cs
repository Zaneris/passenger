using System.Text;
using System.Xml;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace Passenger.Analyzers;

/// <summary>Resource keys as constants, so code names a theme's key as it names any identifier, its home the XAML that gives
/// it: each additional file with KeysClass and KeysPrefix metadata gives that public class in namespace Passenger a const
/// for every x:Key it holds with the prefix, named by the key without it, each further dot an underscore
/// ("Passenger.Editor.Background" is TokenKeys.Editor_Background), marked [IdentifierHome].</summary>
[Generator(LanguageNames.CSharp)]
public sealed class ResourceKeys : IIncrementalGenerator
{
    private const string Xaml = "http://schemas.microsoft.com/winfx/2006/xaml";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<KeysFile> files = context.AdditionalTextsProvider
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select((pair, cancel) => Read(pair.Left, pair.Right.GetOptions(pair.Left), cancel))
            .Where(file => file is not null)!;
        context.RegisterSourceOutput(files.Collect(), (output, all) =>
        {
            foreach (IGrouping<string, KeysFile> group in all.GroupBy(f => f.Class).OrderBy(g => g.Key, StringComparer.Ordinal))
            {
                Write(output, group.Key, group.ToList());
            }
        });
    }

    private static KeysFile? Read(AdditionalText file, AnalyzerConfigOptions options, CancellationToken cancel)
    {
        if (!options.TryGetValue("build_metadata.AdditionalFiles.KeysClass", out string? name) || name.Length == 0
            || !options.TryGetValue("build_metadata.AdditionalFiles.KeysPrefix", out string? prefix) || prefix.Length == 0)
        {
            return null;
        }
        List<string> keys = [];
        string? problem = null;
        try
        {
            using XmlReader reader = XmlReader.Create(new StringReader(file.GetText(cancel)?.ToString() ?? string.Empty));
            while (reader.Read())
            {
                if (reader.NodeType == XmlNodeType.Element && reader.GetAttribute("Key", Xaml) is { } key
                    && key.StartsWith(prefix, StringComparison.Ordinal))
                {
                    keys.Add(key);
                }
            }
        }
        catch (XmlException e)
        {
            problem = e.Message;
        }
        return new KeysFile(name, prefix, Path.GetFileName(file.Path), keys, problem);
    }

    private static void Write(SourceProductionContext output, string name, IReadOnlyList<KeysFile> files)
    {
        Dictionary<string, string> members = new(StringComparer.Ordinal);
        StringBuilder text = new();
        foreach (KeysFile file in files)
        {
            if (file.Problem is not null)
            {
                output.ReportDiagnostic(Diagnostic.Create(Rules.KeysUnread, Location.None, file.Name, name, file.Problem));
                continue;
            }
            foreach (string key in file.Keys)
            {
                string member = key.Substring(file.Prefix.Length).Replace('.', '_');
                if (members.TryGetValue(member, out string? other))
                {
                    if (other != key)
                    {
                        output.ReportDiagnostic(Diagnostic.Create(Rules.KeysUnread, Location.None, file.Name, name,
                            $"\"{key}\" and \"{other}\" would both be {member}"));
                    }
                    continue;
                }
                if (!SyntaxFacts.IsValidIdentifier(member))
                {
                    output.ReportDiagnostic(Diagnostic.Create(Rules.KeysUnread, Location.None, file.Name, name,
                        $"\"{key}\" makes no C# name"));
                    continue;
                }
                members[member] = key;
                text.Append("        public const string ").Append(member).Append(" = \"").Append(key).AppendLine("\";");
            }
        }
        string from = string.Join(", ", files.Select(f => f.Name).Distinct());
        output.AddSource($"{name}.g.cs", SourceText.From($$"""
            // <auto-generated/>
            namespace Passenger
            {
                /// <summary>The resource keys {{from}} give, from there (Passenger.Analyzers' ResourceKeys).</summary>
                [global::Passenger.IdentifierHome]
                public static class {{name}}
                {
            {{text}}    }
            }
            """, Encoding.UTF8));
    }

    private sealed class KeysFile(string name, string prefix, string file, IReadOnlyList<string> keys, string? problem)
    {
        public string Class { get; } = name;
        public string Prefix { get; } = prefix;
        public string Name { get; } = file;
        public IReadOnlyList<string> Keys { get; } = keys;
        public string? Problem { get; } = problem;
    }
}
